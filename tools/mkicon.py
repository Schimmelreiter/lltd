#!/usr/bin/env python3
"""Generates src/icon_default.c: the built-in LLTD icon (Windows .ico with
16x16 and 32x32 32-bit images) - a simple network box with two antennas
and status LEDs, drawn here so that no third-party artwork is needed.

Usage: tools/mkicon.py > src/icon_default.c
"""
import struct
import sys


def draw(size):
    """Returns rows (top to bottom) of (r, g, b, a) pixels."""
    s = size / 32.0
    px = [[(0, 0, 0, 0) for _ in range(size)] for _ in range(size)]

    def rect(x0, y0, x1, y1, col):
        for y in range(int(y0 * s), max(int(y0 * s) + 1, int(y1 * s))):
            for x in range(int(x0 * s), max(int(x0 * s) + 1, int(x1 * s))):
                if 0 <= x < size and 0 <= y < size:
                    px[y][x] = col

    dark = (40, 52, 70, 255)
    body = (70, 110, 170, 255)
    light = (120, 165, 220, 255)
    led = (90, 220, 110, 255)
    # antennas
    rect(7, 4, 9, 17, dark)
    rect(23, 4, 25, 17, dark)
    rect(6.5, 3, 9.5, 5, dark)
    rect(22.5, 3, 25.5, 5, dark)
    # case with outline and highlight
    rect(2, 16, 30, 28, dark)
    rect(3, 17, 29, 27, body)
    rect(3, 17, 29, 19, light)
    # LEDs
    for x in (6, 10, 14, 18):
        rect(x, 22, x + 2, 24, led)
    # feet
    rect(4, 28, 8, 30, dark)
    rect(24, 28, 28, 30, dark)
    return px


def ico_image(size):
    px = draw(size)
    header = struct.pack("<IiiHHIIiiII", 40, size, size * 2, 1, 32, 0, 0, 0, 0, 0, 0)
    xor = bytearray()
    for row in reversed(px):            # BMP rows are bottom-up
        for r, g, b, a in row:
            xor += bytes((b, g, r, a))
    mask_row = ((size + 31) // 32) * 4
    andmask = bytearray()
    for row in reversed(px):
        bits = bytearray(mask_row)
        for x, (_, _, _, a) in enumerate(row):
            if a == 0:
                bits[x // 8] |= 0x80 >> (x % 8)
        andmask += bits
    return header + bytes(xor) + bytes(andmask)


def ico():
    sizes = (16, 32)
    images = [ico_image(sz) for sz in sizes]
    out = struct.pack("<HHH", 0, 1, len(images))
    offset = 6 + 16 * len(images)
    for sz, img in zip(sizes, images):
        out += struct.pack("<BBBBHHII", sz, sz, 0, 0, 1, 32, len(img), offset)
        offset += len(img)
    for img in images:
        out += img
    return out


def main():
    data = ico()
    w = sys.stdout.write
    w("/* Generated by tools/mkicon.py - do not edit. */\n")
    w("#include <stddef.h>\n#include <stdint.h>\n\n")
    w("const uint8_t lltd_default_icon[] = {\n")
    for i in range(0, len(data), 12):
        w("\t" + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",\n")
    w("};\n\nconst size_t lltd_default_icon_len = sizeof(lltd_default_icon);\n")


if __name__ == "__main__":
    main()
